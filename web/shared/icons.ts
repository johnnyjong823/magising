export function iconSvg(name: string): string {
  const rows = ICONS[name] ?? [];
  const w = Math.max(1, ...rows.map((r) => r.length)), h = rows.length || 1;
  let rects = '';
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`; }));
  return `<svg viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges" fill="currentColor" preserveAspectRatio="xMidYMid meet" aria-hidden="true">${rects}</svg>`;
}

export function hydrateIcons(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach((el) => { el.innerHTML = iconSvg(el.dataset.icon!); });
}

export function setIcon(el: HTMLElement, name: string) {
  el.dataset.icon = name;
  el.innerHTML = iconSvg(name);
}
